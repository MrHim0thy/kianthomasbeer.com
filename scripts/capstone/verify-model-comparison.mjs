import { readFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(import.meta.url), ts = require('typescript');
const exports = {};
new Function('exports', ts.transpileModule(await readFile(resolve(root, 'src/content/virginiaModelComparison.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(exports);
const { modelStages, reportedAicModels, modelingContent, aicAxisMaximum, formatModelMetric } = exports;
assert.equal(modelStages.length, 4);
assert.deepEqual(modelStages.map(m => m.metricValue), ['0.6245', '0.6976', '372,927.14', '61,538.84']);
assert.deepEqual(modelStages.filter(m => m.final).map(m => m.id), ['negative-binomial']);
assert.deepEqual(reportedAicModels.map(m => m.aic), [372927.14, 61538.84]);
assert.ok(reportedAicModels.every(m => m.aic > 0 && m.aic < aicAxisMaximum));
assert.equal(formatModelMetric(61538.84), '61,538.84');
assert.deepEqual(modelingContent.crossValidation, { folds: 5, poissonFoldMseSd: 923.35, negativeBinomialFoldMseSd: 890.84 });
assert.match(modelingContent.aicLimitation, /not independently verified/);
assert.equal(modelingContent.technicalDetails.length, 6);
console.log('PASS: Six documented metrics, final selection, common zero-based AIC scale, five-fold summary, and fit-compatibility disclosure verified. No average MSE, residuals, predictions, or statistical significance generated.');
